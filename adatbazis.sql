CREATE DATABASE IF NOT EXISTS Kisprojekt
CHARACTER SET utf8mb4
COLLATE utf8mb4_hungarian_ci;

USE Kisprojekt;

CREATE TABLE IF NOT EXISTS reg (
id INT NOT NULL AUTO_INCREMENT,
nev VARCHAR(255) NOT NULL,
loginnev VARCHAR(100) NOT NULL,
jelszo VARCHAR(255) NOT NULL,
szerepkor VARCHAR(20) NOT NULL,
auto BOOLEAN NOT NULL DEFAULT TRUE,
pc BOOLEAN NOT NULL DEFAULT TRUE,
mobil VARCHAR(255) NOT NULL,
email VARCHAR(255) NOT NULL,

PRIMARY KEY (id),

UNIQUE KEY uq_reg_loginnev (loginnev),
UNIQUE KEY uq_reg_email (email)
);